"""
cca_potts_aggregate.py — Re-aggregate observables_by_config.csv from raw/*.npz.

Use when:
  - Raw runs were generated by multiple sweeps (e.g. q=2 pilot + q=5,7,10 extension)
    that each overwrote the by_config CSV
  - Want to regenerate CSV without re-running MC

Reads every run_q{q}_L{L}_T{t}_rep{r}.npz in raw/, extracts the 'meta' JSON
payload from each (which contains all scalar observables), and writes a unified
observables_by_config.csv and observables_mean_sem.csv.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
import re

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

from cca_potts_sweep_main import (
    write_csv, aggregate_replicas, DERIVED_DIR, RAW_DIR,
)


RUN_NAME_RE = re.compile(r"run_q(\d+)_L(\d+)_T(\d+)_rep(\d+)\.npz$")


def aggregate_from_raw(raw_dir: Path = RAW_DIR) -> tuple[list, list]:
    """Read all .npz files in raw_dir, return (rows, aggregated_rows)."""
    rows = []
    for path in sorted(raw_dir.glob("run_q*_L*_T*_rep*.npz")):
        m = RUN_NAME_RE.search(path.name)
        if not m:
            continue
        data = np.load(path, allow_pickle=True)
        meta_raw = data["meta"]
        # meta is a 0-d object array containing a JSON string
        if hasattr(meta_raw, "item"):
            meta_str = str(meta_raw.item())
        else:
            meta_str = str(meta_raw)
        row = json.loads(meta_str)
        rows.append(row)
    agg = aggregate_replicas(rows)
    return rows, agg


def main():
    rows, agg = aggregate_from_raw()
    if not rows:
        print("No .npz files found in raw/")
        return
    write_csv(rows, DERIVED_DIR / "observables_by_config.csv")
    write_csv(agg, DERIVED_DIR / "observables_mean_sem.csv")
    print(f"Aggregated {len(rows)} runs → {len(agg)} (q, L, T) configs")
    print(f"  wrote {DERIVED_DIR}/observables_by_config.csv")
    print(f"  wrote {DERIVED_DIR}/observables_mean_sem.csv")


if __name__ == "__main__":
    main()
